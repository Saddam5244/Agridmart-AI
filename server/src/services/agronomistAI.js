// 🔍 AUTOMATIC LANGUAGE DETECTION
// ==========================================
export function detectLanguage(text = "", preferredLang = "") {
  if (!text) return preferredLang || "hi";
  const str = text.trim();

  // 1. Unicode Script Checks (Direct Native Script Identification)
  if (/[\u0A00-\u0A7F]/.test(str)) return "pa"; // Gurmukhi (Punjabi)
  if (/[\u0980-\u09FF]/.test(str)) return "bn"; // Bengali
  if (/[\u0A80-\u0AFF]/.test(str)) return "gu"; // Gujarati
  if (/[\u0B80-\u0BFF]/.test(str)) return "ta"; // Tamil
  if (/[\u0C00-\u0C7F]/.test(str)) return "te"; // Telugu
  if (/[\u0C80-\u0CFF]/.test(str)) return "kn"; // Kannada

  // 2. Devanagari script: differentiate Marathi, Bhojpuri, Hindi
  if (/[\u0900-\u097F]/.test(str)) {
    // Bhojpuri indicators (avoid false positives like 'बाजार' or 'बात')
    if (/(?:^|\s)बा(?:[\s,.!?]|$)|(?:^|\s)का\s*बा|बाटे|बावे|भइला|भइल|रउआ|हमार|गइल|करीं|खातिर|पियर|कहाँ होला|का होला|दिहीं|केतना|हईं|कइसे|छींटीं|सकीलें|पटवन|जादे/.test(str)) {
      return "bho";
    }
    // Marathi indicators
    if (/(आहे|नाही|करा|पाने|पिवळे|पिवळी|पिकांची|कुठे होते|कशी करावी|औषध|काय आहे|भाव|गव्हाचा|गहू|तांदूळ|खत|पाणी|शेतकरी|तांबेरा|फवारणी|बाजार भाव)/.test(str)) {
      return "mr";
    }
    if (preferredLang === "mr" || preferredLang === "bho") {
      return preferredLang;
    }
    return "hi"; // Hindi (default for Devanagari)
  }

  // 3. Latin / English alphabet
  const lower = str.toLowerCase();

  // If user selected an explicit regional language preference (pa, mr, gu, bn, te, ta, kn, bho)
  // and entered prompt in Roman/English script:
  if (preferredLang && !['en', 'hi'].includes(preferredLang)) {
    return preferredLang;
  }

  // Hinglish / Romanized Hindi keywords
  const isHinglish = /(khet|pani|paani|fasal|khad|chala|patwan|peela|peeli|patti|kare|spray|daal|dawa|davai|mandi|bhav|yojana|gehu|sarson|sbse jaada|sabse jyada|kaha hoti|kahan hoti|kisan|kheti|mitti|kaise|kitna|tamatar|aloo|dhaan|ilaj|chalu)/.test(lower);
  if (isHinglish) {
    if (preferredLang === "mr") return "mr";
    if (preferredLang === "bho") return "bho";
    return "hi";
  }

  // Standard English inquiry vocabulary
  const isEnglish = /(what|which|how|where|when|why|who|is|are|the|in|for|to|of|crop|farming|state|production|agriculture|fertilizer|spray|disease|treatment|dose|price|market|pump|irrigation|soil|pest|yield|subsidy|scheme|wheat|paddy|rice|potato|tomato|mustard|cotton|cattle|dairy|organic|water)/.test(lower);
  if (isEnglish) {
    return "en";
  }

  return preferredLang || "en";
}

