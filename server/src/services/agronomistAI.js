// 🧹 CLEAN TEXT FOR SPEECH SYNTHESIS
// ==========================================
function cleanSpeechText(text = "") {
  return text
    .replace(/[*#_`~[\]()]/g, "")
    .replace(/https?:\/\/\S+/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

