export function isAgricultureDomain(query = "") {
  if (!query || query.trim().length < 2) return false;
  const q = query.toLowerCase();

  // Out-of-Domain Blocklist Patterns
  const outOfDomainPatterns = [
    /\b(cricket|ipl|football|messi|ronaldo|virat kohli|rohit sharma|dhoni|match score|world cup)\b/,
    /\b(movie|cinema|actor|actress|salman khan|shahrukh|bollywood|hollywood|song|lyrics|trailer)\b/,
    /\b(python code|javascript|html|css|react|c\+\+|java code|debug code|write a function|algorithm|sql query)\b/,
    /\b(who is the president|who is prime minister|narendra modi|rahul gandhi|election result|parliament|politics)\b/,
    /\b(cryptocurrency|bitcoin|ethereum|stock market trading|forex|option trading)\b/,
    /\b(joke|story|poem|shayari|love letter|relationship advice|astrology|horoscope|zodiac|rashifal)\b/,
    /\b(iphone|samsung galaxy|laptop review|playstation|gaming|pubg|free fire)\b/,
    /(क्रिकेट|मैच स्कोर|विराट कोहली|रोहित शर्मा|आईपीएल|फिल्म|मूवी|गाना|शायरी|कविता|राजनीति|चुनाव|प्रधानमंत्री|पायथन कोड)/
  ];

  for (const pattern of outOfDomainPatterns) {
    if (pattern.test(q)) {
      const hasAgriTerm = /(kisan|kheti|fasal|crop|soil|farmer|agriculture|irrigation|mandi|fertilizer|dawa|seed|gehu|paddy|wheat|खेती|किसान|फसल|खाद|मिट्टी|कृषि|पटवन|सिंचाई|ਕਣਕ|ਗੋਧੂਮ|వరి|ನೆಲ್ಲು|பயிர்)/.test(q);
      if (!hasAgriTerm) return false;
    }
  }

  return true;
}

